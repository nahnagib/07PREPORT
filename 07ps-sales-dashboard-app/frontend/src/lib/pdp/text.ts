export function formatKpi(value: number | null, unit: string): string {
  if (value === null || value === undefined) return '—';
  if (unit === 'pct') return `${value.toFixed(1)}%`;
  if (unit === 'days') return `${value.toFixed(1)} days`;
  return String(value);
}

/** "Target ≥ 80%", "Target ≤ 60 days", "Target 3" */
export function formatTarget(target: number, comparator: string, unit: string): string {
  const op = comparator === 'gte' ? '≥ ' : comparator === 'lte' ? '≤ ' : '';
  return `Target ${op}${unit === 'pct' ? `${target}%` : unit === 'days' ? `${target} days` : target}`;
}
